export function getStudyDays(year) {

    const selectedYear = String(year);

    return Object.fromEntries(

        Object.entries(studyDays).filter(
            ([date]) => date.startsWith(selectedYear)
        )

    );

}


export function getAvailableStudyYears() {

    const years = Object.keys(studyDays).map(
        date => Number(date.slice(0, 4))
    );

    return [...new Set(years)].sort(
        (yearA, yearB) => yearB - yearA
    );

}